/** Кол-во брендов — считается из списка, не хардкодится (TBD §3: «бренды пусть посчитает»). */
export const BRANDS_COUNT = BRANDS.length;

export function getBrand(slug: string): Brand | undefined {
  return BRANDS.find((b) => b.slug === slug);
}

/** Имя бренда → slug (для связи Product.brand ↔ страница бренда). */
export function brandSlugByName(name: string): string | undefined {
  return BRANDS.find((b) => b.name === name)?.slug;
}
